/** First private-use code point: CGRAM glyph n arrives as this + n (see lcdController). */
export const LCD_CUSTOM_CHAR_BASE = 0xe000;

/**
 * Glyph for one displayed character. CGRAM characters come in as private-use
 * code points and are drawn from the design's own glyph rows.
 */
export function lcdDotGlyph(character: string, custom?: readonly (readonly string[])[]): LcdDotGlyph {
  const code = character.charCodeAt(0);
  if (code >= LCD_CUSTOM_CHAR_BASE && code < LCD_CUSTOM_CHAR_BASE + 8) {
    const rows = custom?.[code - LCD_CUSTOM_CHAR_BASE];
    return rows && rows.length === 8 ? (rows as unknown as LcdDotGlyph) : LCD_GLYPHS[' '];
  }
  return LCD_GLYPHS[character] ?? LCD_GLYPHS[character.toUpperCase()] ?? LCD_GLYPHS['?'];
}


