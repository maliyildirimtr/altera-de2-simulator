/** Console/log lines with variable parts: English pattern → Turkish. */
const MESSAGE_PATTERNS: Array<[RegExp, (m: RegExpExecArray) => string]> = [
  [/^Compiled "(.+)" successfully \((\d+) inputs, (\d+) outputs\)\. Press Run to start\.$/, (m) => `"${m[1]}" başarıyla derlendi (${m[2]} giriş, ${m[3]} çıkış). Başlatmak için Çalıştır'a bas.`],
  [/^Compilation failed: (.*)$/, (m) => `Derleme başarısız: ${m[1]}`],
  [/^Line (\d+): (.*)$/, (m) => `Satır ${m[1]}: ${m[2]}`],
  [/^Auto-detected (\d+) ports from top module\.$/, (m) => `Üst modülden ${m[1]} port otomatik algılandı.`],
  [/^Loaded example into DE2: (.*)$/, (m) => `Örnek DE2'ye yüklendi: ${m[1]}`],
  [/^Quartus project exported: (\S+) \((\d+) pins, Cyclone II EP2C35F672C6\)\. Open (\S+) in Quartus II 13\.0 SP1\.$/, (m) => `Quartus projesi indirildi: ${m[1]} (${m[2]} pin, Cyclone II EP2C35F672C6). ${m[3]} dosyasını Quartus II 13.0 SP1 ile aç.`],
  [/^No DE2 pin for: (.*)\. Map them in Pin Mapping or add them in Quartus\.$/, (m) => `Şunların DE2 pini yok: ${m[1]}. Pin eşlemeden eşle ya da Quartus'ta ekle.`],
  [/^Some logic could not be simulated and is ignored: (.*)$/, (m) => `Mantığın bir kısmı simüle edilemedi ve yok sayıldı: ${m[1]}`],
  [/^Export failed: (.*)$/, (m) => `Dışa aktarma başarısız: ${m[1]}`],
];

/** Translate a whole UI or log string for `lang`. Unknown text is returned unchanged. */
export function translateText(text: string, lang: string): string {
  if (lang !== 'tr') return text;
  const direct = TOOL_TR[text];
  if (direct !== undefined) return direct;
  for (const [re, fn] of MESSAGE_PATTERNS) {
    const m = re.exec(text);
    if (m) return fn(m);
  }
  return text;
}

/** Translator for the current language: `t('Compile')`. */
export function useT(): (text: string) => string {
  const { lang } = useI18n();
  return useCallback((text: string) => translateText(text, lang), [lang]);
}
